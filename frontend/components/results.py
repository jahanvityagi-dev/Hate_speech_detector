

import streamlit as st
from datetime import datetime
import io
import csv
from core.models import ModerationResult
from services.session import SessionState


def _generate_export_csv(result: ModerationResult, transcription: str = None) -> str:
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "Input Text", "Transcription", "Label", "Classification Reason",
        "Explanation", "Action", "Action Reason", "Policy Snippets"
    ])
    policy_texts = " | ".join([p.get("text", "") for p in result.policy_snippets])
    writer.writerow([
        result.input_text,
        transcription or "",
        result.label,
        result.classification_reason,
        result.explanation,
        result.action,
        result.action_reason,
        policy_texts
    ])
    return output.getvalue()


def _generate_export_text(result: ModerationResult, transcription: str = None) -> str:
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    export_text = f"""HATE SPEECH DETECTION REPORT\nGenerated: {timestamp}\n\nINPUT TEXT:\n{result.input_text}\n"""
    if transcription:
        export_text += f"\nTRANSCRIPTION:\n{transcription}\n"
    export_text += f"""
CLASSIFICATION LABEL: {result.label}\n
CLASSIFICATION REASON:\n{result.classification_reason}\n
DETAILED EXPLANATION:\n{result.explanation}\n
RELEVANT POLICY SNIPPETS:
"""
    for i, policy in enumerate(result.policy_snippets, 1):
        export_text += f"""
{i}. Source: {policy.get('source_file', 'Unknown')}\n   Content: {policy.get('text', 'N/A')}\n   Relevance Score: {policy.get('score', 'N/A')}\n"""
    export_text += f"""
\nRECOMMENDED ACTION: {result.action}\n
ACTION REASON:\n{result.action_reason}\n
Report generated by Hate Speech Detection System\n"""
    return export_text


def render_results(result: ModerationResult, transcription: str = None):
    st.markdown('<h2 class="section-header">📊 Analysis Results</h2>', unsafe_allow_html=True)
    st.markdown('<div class="results-container">', unsafe_allow_html=True)

    if transcription:
        st.markdown("### 🎙️ Transcription")
        st.info(f"**Transcribed Text**: {transcription}")

    st.markdown("### 🏷️ Classification")
    st.markdown(f"**Label**: `{result.label}`")

    if result.classification_reason:
        st.markdown("### 🤖 Classification Reasoning")
        st.info(result.classification_reason)

    if result.explanation:
        st.markdown("### 💡 Policy-Based Explanation")
        st.write(result.explanation)

    if result.policy_snippets:
        st.markdown("### 📜 Relevant Policy Snippets")
        for i, policy in enumerate(result.policy_snippets, 1):
            with st.expander(
                f"Policy {i}: {policy.get('source_file', 'Unknown')} (Score: {policy.get('score', 'N/A')})"):
                st.markdown(f"""
                **Source:** {policy.get('source_file', 'N/A')}  
                **Relevance Score:** {policy.get('score', 'N/A')}  
                **Content:**  
                {policy.get('text', 'N/A')}
                """)

    if result.action:
        st.markdown("### ⚡ Recommended Moderation Action")
        st.markdown(f"""
        **Action:** {result.action}  
        **Reason:** {result.action_reason}
        """)

    export_csv = _generate_export_csv(result, transcription)
    export_text = _generate_export_text(result, transcription)

    col1, col2 = st.columns(2)
    with col1:
        st.download_button(
            label="📄 Export as CSV",
            data=export_csv,
            file_name=f"moderation_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.csv",
            mime="text/csv",
            use_container_width=True
        )
    with col2:
        st.download_button(
            label="📝 Export as TXT",
            data=export_text,
            file_name=f"moderation_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.txt",
            mime="text/plain",
            use_container_width=True
        )

    st.markdown('</div>', unsafe_allow_html=True)
